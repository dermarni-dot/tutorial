"""Uploads the skin surface maps (bake_skin.py: tools/body/out/skin/T<n>/<Part>_{color,normal,rough}.png) as Image
assets with Open Cloud and writes the game's two generated files:

    src/shared/BodySurfaceData.lua         ids, sizes, the frame -> surface tier shift, the texture budget
    src/shared/BodySurfaceSet.model.json   the authored SurfaceAppearances (Rojo writes their ColorMap / NormalMap /
                                           RoughnessMap: scripts cannot, the maps are PluginSecurity) under
                                           ReplicatedStorage.Shared.BodySurfaceSet.T<n>.<Part>; BodySurfaces.lua
                                           clones them onto the swapped body parts

    python3 tools/body/publish_skin.py [--dry-run] [--wait 600] [--check]

Same cache as the meshes (tools/body/uploaded.json, SHA-256 -> id), so a re-run uploads only what changed.
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import publish_body as pb  # noqa: E402  (hp with the body cache, check_all)

hp = pb.hp
SKIN = os.path.join(HERE, "out", "skin")
DATA = os.path.join(ROOT, "src", "shared", "BodySurfaceData.lua")
MODEL = os.path.join(ROOT, "src", "shared", "BodySurfaceSet.model.json")
KINDS = (("color", "ColorMap"), ("normal", "NormalMap"), ("rough", "RoughnessMap"))


def texture_bytes(size, kind):
    """GPU memory of one map, block-compressed as engines usually keep them (BC1 for the opaque greyscale colour and
    roughness, BC3 / BC5-class for the normal map: 0.5 / 1 byte per texel) and uncompressed RGBA8 (4), x 4/3 mips"""
    texels = size * size * 4 / 3
    return int(texels * (1.0 if kind == "normal" else 0.5)), int(texels * 4)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--wait", type=int, default=600)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    sj = json.load(open(os.path.join(SKIN, "skin.json")))
    cache = hp.load_cache()
    before = set(v["id"] for v in cache.values())
    tiers, used = {}, []
    comp = raw = 0
    for tn in sorted(sj["tiers"], key=int):
        tiers[int(tn)] = {}
        for part, e in sorted(sj["tiers"][tn].items()):
            rec = {"size": e["size"]}
            for kind, prop in KINDS:
                path = os.path.join(HERE, e["files"][kind])
                aid = hp.ensure(cache, path, "Image", "WCB Skin T%s %s %s" % (tn, part, kind),
                                "Become a World Class Boxer: body skin %s map, tier %s %s" % (kind, tn, part),
                                "image/png", a.dry_run, None)
                rec[kind] = aid
                used.append(aid)
                c, r = texture_bytes(e["size"], kind)
                comp += c
                raw += r
            tiers[int(tn)][part] = rec
    if a.dry_run:
        print("dry run: %d images referenced" % len(used))
        return
    new = [i for i in used if i and i not in before]
    ids = used if a.check else new
    if ids:
        print("moderation:", pb.check_all(cache, ids, a.wait))
    hp.save_cache(cache)
    missing = sum(1 for i in used if not i)
    # one boxer's worst case: every part on its own surface tier is at most one set per part type
    per_set, per_raw = {}, {}
    for part, size in sj["parts"].items():
        per_set[part] = sum(texture_bytes(size, k)[0] for k, _ in KINDS)
        per_raw[part] = sum(texture_bytes(size, k)[1] for k, _ in KINDS)
    data = {
        "version": 1,
        "shift": sj["shift"],
        "parts": sj["parts"],
        "tiers": tiers,
        "budget": {"allCompressed": comp, "allRaw": raw, "perBoxerCompressed": sum(per_set.values()),
                   "perBoxerRaw": sum(per_raw.values())},
    }
    head = ("-- GENERATED by tools/body/publish_skin.py from tools/body/out/skin (bake_skin.py) and the upload cache\n"
            "-- tools/body/uploaded.json. Do not edit by hand. The SurfaceAppearances themselves are authored in\n"
            "-- BodySurfaceSet.model.json (scripts may not write their maps); BodySurfaces.lua clones them.\n")
    with open(DATA, "w") as f:
        f.write(head + "return " + hp.lua(data) + "\n")
    model = {"ClassName": "Folder", "Children": []}
    for tn in sorted(tiers):
        folder = {"Name": "T%d" % tn, "ClassName": "Folder", "Children": []}
        for part, rec in sorted(tiers[tn].items()):
            props = {prop: "rbxassetid://%d" % rec[kind] for kind, prop in KINDS if rec[kind]}
            folder["Children"].append({"Name": part, "ClassName": "SurfaceAppearance", "Properties": props})
        model["Children"].append(folder)
    with open(MODEL, "w") as f:
        json.dump(model, f, indent=1)
        f.write("\n")
    print("wrote %s and %s: %d tiers, %d images, %d missing; texture memory all sets %.1f MB compressed (%.1f MB raw),"
          " one boxer's set %.1f MB compressed" % (os.path.relpath(DATA, ROOT), os.path.relpath(MODEL, ROOT),
                                                   len(tiers), len(used), missing, comp / 2 ** 20, raw / 2 ** 20,
                                                   data["budget"]["perBoxerCompressed"] / 2 ** 20))


if __name__ == "__main__":
    main()
