"""Uploads the icon sheets and the title logo (tools/ui/out, from build_icons.py) to Roblox as Image assets with
Open Cloud, checks their moderation, and writes src/shared/IconData.lua.

    python3 tools/ui/publish_icons.py              # upload what changed, check moderation, write the manifest
    python3 tools/ui/publish_icons.py --check      # only re-read the moderation state of every cached upload
    python3 tools/ui/publish_icons.py --zero       # write the manifest with every id 0 (the game draws text fallbacks)

* Creator: ROBLOX_CREATOR_ID / ROBLOX_CREATOR_TYPE (group | user). API key: x-api-key from ROBLOX_API_KEY unless
  the proxy injects it (then leave it unset).
* Every upload is cached by the PNG's SHA-256 in tools/ui/uploaded.json (id, moderation state), so a re-run uploads
  only a sheet that changed and the ids the game uses stay stable.
"""
import argparse
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "tools", "hair"))
import publish as hair  # noqa: E402  (the shared Open Cloud upload code: _request, upload, sha)

OUT = os.path.join(HERE, "out")
CACHE = os.path.join(HERE, "uploaded.json")
MANIFEST = os.path.join(ROOT, "src", "shared", "IconData.lua")
API = "https://apis.roblox.com/assets/v1"


def load_cache():
    if os.path.exists(CACHE):
        with open(CACHE) as fh:
            return json.load(fh)
    return {}


def save_cache(c):
    with open(CACHE, "w") as fh:
        json.dump(c, fh, indent=1, sort_keys=True)


def moderation(asset_id):
    r = hair._request("GET", f"{API}/assets/{asset_id}?readMask=moderationResult,state")
    return (r.get("moderationResult") or {}).get("moderationState", "?"), r.get("state", "?")


def ensure(cache, path, name, desc):
    h = hair.sha(path)
    e = cache.get(h)
    if e and e.get("id"):
        return e
    aid, state = hair.upload(path, "Image", name, desc, "image/png")
    e = {"id": aid, "file": os.path.relpath(path, ROOT), "moderation": state, "uploaded": time.strftime("%Y-%m-%d %H:%M:%S")}
    cache[h] = e
    save_cache(cache)
    print(f"uploaded {os.path.basename(path)} -> {aid} ({state})")
    return e


def bodymap_id(cache):
    """the uploaded id of the current tools/ui/out/bodymap.png (build_bodymap.py), 0 when not uploaded"""
    path = os.path.join(OUT, "bodymap.png")
    if not os.path.exists(path):
        return 0
    e = cache.get(hair.sha(path))
    return int(e["id"]) if e and e.get("id") else 0


def set_bodymap_line(txt, body_id, state):
    """IconData.bodyMap = id (replaced, or added before the return)"""
    import re
    line = f"IconData.bodyMap = {body_id} -- the Body screen's muscle-map sheet (build_bodymap.py; cells in BodyMapData), moderation {state}"
    if re.search(r"^IconData\.bodyMap = .*$", txt, flags=re.M):
        return re.sub(r"^IconData\.bodyMap = .*$", line, txt, flags=re.M)
    return txt.replace("return IconData", line + "\nreturn IconData")


def lua_manifest(doc, sheet_ids, logo_id, states):
    L = []
    L.append("-- IconData: the game's icon set and title logo as uploaded Image assets. GENERATED by")
    L.append("-- tools/ui/publish_icons.py from tools/ui/out (tools/ui/build_icons.py) - do not edit by hand.")
    L.append("-- icons[name] = { id = sheet asset id, x, y = the cell's offset on its sheet (ImageRectOffset) };")
    L.append("-- every cell is `cell` px square (ImageRectSize). An id of 0 = not uploaded: UI.Icon draws its fallback.")
    L.append("-- The glyphs are white on transparent: tint with ImageColor3.")
    L.append("-- logo: the full-colour lockup (colour rect) and its white silhouette (mask rect) on one 1024 x 1024 image.")
    L.append("local IconData = {}")
    L.append(f"IconData.cell = {doc['cell']}")
    L.append("IconData.sheets = { " + ", ".join(str(i) for i in sheet_ids) + " }")
    L.append("IconData.moderation = { " + ", ".join(f'"{s}"' for s in states) + " } -- sheets then the logo, when published")
    L.append("IconData.icons = {")
    for name in doc["order"]:
        m = doc["icons"][name]
        L.append(f"\t{name} = {{ id = {sheet_ids[m['sheet'] - 1]}, x = {m['x']}, y = {m['y']} }},")
    L.append("}")
    lg = doc["logo"]
    L.append("IconData.logo = {")
    L.append(f"\tid = {logo_id},")
    L.append("\tsize = Vector2.new(1024, 1024),")
    for k in ("colour", "mask"):
        r = lg[k]
        L.append(f"\t{k} = {{ x = {r['x']}, y = {r['y']}, w = {r['w']}, h = {r['h']} }},")
    L.append("}")
    L.append("return IconData")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--zero", action="store_true")
    ap.add_argument("--bodymap", action="store_true", help="upload tools/ui/out/bodymap.png (build_bodymap.py) and write its id into src/shared/IconData.lua (bodyMap)")
    a = ap.parse_args()
    if a.bodymap:
        cache = load_cache()
        sheet = os.path.join(OUT, "bodymap.png")
        e = ensure(cache, sheet, "WCB Body Map", "World Class Boxer: the Body tab's muscle map (white masks, tinted in game).")
        st, state = moderation(e["id"])
        e["moderation"] = st
        save_cache(cache)
        manifest = MANIFEST
        with open(manifest) as fh:
            txt = fh.read()
        txt = set_bodymap_line(txt, e["id"], st)
        with open(manifest, "w") as fh:
            fh.write(txt)
        print(f"bodymap.png: {e['id']}  moderation {st}  state {state}; wrote {os.path.relpath(manifest, ROOT)}")
        return
    with open(os.path.join(OUT, "icons.json")) as fh:
        doc = json.load(fh)
    cache = load_cache()
    if a.check:
        for h, e in cache.items():
            st, state = moderation(e["id"])
            e["moderation"] = st
            print(f"{e['file']}: {e['id']}  moderation {st}  state {state}")
        save_cache(cache)
        return
    files = [os.path.join(OUT, s) for s in doc["sheets"]]
    logo = os.path.join(OUT, doc["logo"]["file"])
    if a.zero:
        sheet_ids, logo_id, states = [0] * len(files), 0, []
    else:
        sheet_ids, states = [], []
        for i, p in enumerate(files):
            e = ensure(cache, p, f"WCB UI Icons {i + 1}", "World Class Boxer interface icons (white glyphs, tinted in game).")
            sheet_ids.append(e["id"])
        le = ensure(cache, logo, "WCB Title Logo", "Become a World Class Boxer: title screen logo.")
        logo_id = le["id"]
        # moderation: poll a little while any is still pending
        for _ in range(10):
            pending = False
            states = []
            for p in files + [logo]:
                e = cache[hair.sha(p)]
                st, _state = moderation(e["id"])
                e["moderation"] = st
                states.append(st)
                pending = pending or st not in ("Approved", "Rejected")
            save_cache(cache)
            if not pending:
                break
            time.sleep(6)
        for p, st in zip(files + [logo], states):
            print(f"{os.path.basename(p)}: {cache[hair.sha(p)]['id']}  moderation {st}")
    txt = lua_manifest(doc, sheet_ids, logo_id, states)
    bid = 0 if a.zero else bodymap_id(cache)
    txt = set_bodymap_line(txt, bid, (cache.get(hair.sha(os.path.join(OUT, "bodymap.png"))) or {}).get("moderation", "-") if bid else "-")
    with open(MANIFEST, "w") as fh:
        fh.write(txt)
    print(f"wrote {os.path.relpath(MANIFEST, ROOT)}")


if __name__ == "__main__":
    main()
