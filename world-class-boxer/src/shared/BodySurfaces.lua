-- BodySurfaces (v16): the skin surface maps on the muscle-tier body parts. Each swapped full-detail part gets a clone
-- of the authored SurfaceAppearance for its (surface tier, part type): a tangent-space NormalMap (pores, striations,
-- veins, creases), a near-white greyscale ColorMap (the ambient occlusion and cavity) and a RoughnessMap.
--
-- * Scripts may not write a SurfaceAppearance's ColorMap / NormalMap / RoughnessMap (PluginSecurity), so the maps are
--   authored into the place by Rojo (BodySurfaceSet.model.json -> ReplicatedStorage.Shared.BodySurfaceSet.T<n>.<Part>,
--   generated by tools/body/publish_skin.py) and cloned here; Color and AlphaMode are script-writable.
-- * Skin tone: SurfaceAppearance.Color tints the ColorMap (a multiplier; the map is white where nothing is occluded),
--   and the MeshPart's own Color no longer shows once a SurfaceAppearance with an opaque ColorMap covers it. So the
--   clone's Color follows the part's Color: set at the swap, and kept in step by a Color-changed connection (any code
--   that recolours the part - the skin tone, a flush - recolours the tint too).
-- * Sharing: one set per (surface tier, part type) serves every frame (the UVs and the grooves' places are the same on
--   every frame); a frame's surface tier is its body tier minus BodySurfaceData.shift[frame] (Power Build one softer,
--   Heavyweight Build two). Left limbs share the right limb's set. Hands, feet and the LowerTorso (gloves / wraps,
--   boots, trunks) and every lite (crowd) part get none.
local Shared = script.Parent

local BodySurfaces = {}

local okData, Data = pcall(function()
	return require(Shared:FindFirstChild("BodySurfaceData"))
end)
if not okData or type(Data) ~= "table" then
	Data = { shift = {}, parts = {}, tiers = {} }
end
BodySurfaces.Data = Data

BodySurfaces.NAME = "BodySkin"
BodySurfaces.BASE = {
	UpperTorso = "UpperTorso",
	LeftUpperArm = "UpperArm",
	RightUpperArm = "UpperArm",
	LeftLowerArm = "LowerArm",
	RightLowerArm = "LowerArm",
	LeftUpperLeg = "UpperLeg",
	RightUpperLeg = "UpperLeg",
	LeftLowerLeg = "LowerLeg",
	RightLowerLeg = "LowerLeg",
}

local source = nil -- a test (or a tool) may hand over its own folder of T<n> folders
function BodySurfaces.SetSource(folder)
	source = folder
end

local function setFolder()
	if source then
		return source
	end
	return Shared:FindFirstChild("BodySurfaceSet")
end
BodySurfaces.Folder = setFolder

-- the surface tier a part of body tier `tier` on `frame` wears
function BodySurfaces.TierFor(frame, tier)
	tier = tonumber(tier) or 0
	if tier < 1 then
		return nil
	end
	local shift = (Data.shift and Data.shift[frame]) or 0
	return math.max(1, tier - shift)
end

-- the authored SurfaceAppearance for (body tier, part name, frame), or nil
function BodySurfaces.Template(tier, partName, frame)
	local base = BodySurfaces.BASE[partName]
	local st = base and BodySurfaces.TierFor(frame, tier)
	local f = st and setFolder()
	local tf = f and f:FindFirstChild("T" .. st)
	local sa = tf and tf:FindFirstChild(base)
	if sa and sa:IsA("SurfaceAppearance") then
		return sa
	end
	return nil
end

local function follow(part, sa)
	sa.Color = part.Color
	part:GetPropertyChangedSignal("Color"):Connect(function()
		if sa.Parent == part then
			sa.Color = part.Color
		end
	end)
end

-- gives a swapped body part its skin surface (or takes it off: a lite part, a part type without maps, no authored set);
-- reads the part's BodyTier / BodyFrame / BodyLite attributes. Returns the SurfaceAppearance or nil
function BodySurfaces.Attach(part)
	if not (part and part:IsA("BasePart")) then
		return nil
	end
	local old = part:FindFirstChild(BodySurfaces.NAME)
	if old then
		old:Destroy()
	end
	if part:GetAttribute("BodyLite") then
		return nil
	end
	local t = BodySurfaces.Template(part:GetAttribute("BodyTier"), part.Name, part:GetAttribute("BodyFrame"))
	if not t then
		return nil
	end
	local sa = t:Clone()
	sa.Name = BodySurfaces.NAME
	follow(part, sa)
	sa.Parent = part
	return sa
end

-- every body part's tint back on its part's Color (after a bulk recolour that bypassed the connection, e.g. a clone)
function BodySurfaces.Sync(model)
	for name in pairs(BodySurfaces.BASE) do
		local p = model and model:FindFirstChild(name)
		local sa = p and p:FindFirstChild(BodySurfaces.NAME)
		if sa then
			sa.Color = p.Color
		end
	end
end

return BodySurfaces
